"""
RerConvergeTab: field specification of the RERconverge module (conf/rerconverge.config).

Off by default (RerConfig.enabled is False in gui/models/modules.py). The four
rer_tool sub-steps (build_trait, build_tree, build_matrix, continuous) are
checkboxes that jointly build --rer_tool (gui/generation/context.py), as the CAAS
tab does for --ct_tool.

There is no gene-set mode: RERconverge runs genome-wide on the full gene trees.
main.nf passes Channel.empty() for both optional gene-set inputs of RER_MAIN
(workflows/rerconverge.nf), which does not use them, so a mode selector here would
have no effect.

Imported by: gui/widgets/main_window.py
"""

# ── Third-party ───────────────────────────────────────────────────────────────
from PySide6.QtWidgets import QCheckBox, QLabel

# ── Local ─────────────────────────────────────────────────────────────────────
from gui.models.modules import RerConfig
from gui.widgets.common.module_tab import ModuleTabWidget
from gui.widgets.common.specs import FieldSpec, ModuleTabSpec, Section

SPEC = ModuleTabSpec(
    title="RERconverge",
    blurb=(
        "Correlates relative evolutionary rates (RER) across gene trees with the "
        "phenotype, using permutation batches for significance."
    ),
    disclaimer=(
        "Scoring needs this module's output when it's off. Check 'Use precomputed "
        "RERconverge output' on the Precomputed Run tab — it's auto-derived per "
        "phenotype from one base path, no per-row entry needed."
    ),
    essential_fields=(
        Section("RER trait analysis"),
        # Selects the statistical model applied to the trait (continuous or
        # binary RERconverge machinery): a model-selection parameter.
        FieldSpec(
            name="rer_trait_mode", help="Trait model routing: auto detects continuous or binary from the trait; continuous or binary forces that model.",
            label="Trait type routing",
            kind="choice",
            choices=("auto", "continuous", "binary"),
            importance="default",
        ),
        # The transform affects the validity of the RER-trait correlation, so it
        # counts as a model-selection parameter.
        FieldSpec(
            name="rer_transform", help="Trait transform: ha_logit = Haldane-Anscombe logit (needs n_trait and c_trait); logit, arcsin, log10, none; auto chooses from the data.",
            label="Trait transform",
            kind="choice",
            choices=("ha_logit", "auto", "logit", "arcsin", "log10", "none"),
            importance="default",
        ),
        # Empirical activity and BH highlighting use the shared Scoring thresholds.
        # Required: gui/generation/validate.py demands it whenever the module is
        # enabled, and the pipeline has no way to generate it.
        FieldSpec(
            name="gene_trees",
            label="Gene trees file",
            kind="path_file",
            help="Per-gene trees file, one tree per alignment; required whenever RERconverge runs and not generated by this pipeline.",
            importance="required",
        ),
    ),
    advanced_fields=(
        Section("Gene tree and matrix output paths"),
        FieldSpec(name="trait_out", help="Output path of the build_trait step (polished trait file).", label="Trait output path (build_trait)", importance="optional"),
        FieldSpec(name="trees_out", help="Output path of the build_tree step (pruned master tree of the gene trees).", label="Trees output path (build_tree)", importance="optional"),
        FieldSpec(name="matrix_out", help="Output path of the build_matrix step (RER matrix).", label="Matrix output path (build_matrix)", importance="optional"),
        Section("Quality thresholds and winsorization"),
        FieldSpec(name="rer_minsp", help="Minimum species a gene needs to enter the RER analysis; default 15.", label="Minimum species per gene", importance="default"),
        FieldSpec(name="winsorize_rer", help="Winsorization threshold for RER values, which limits the leverage of outlier branches; default 3.", label="Winsorize RER threshold", importance="default"),
        FieldSpec(name="winsorize_trait", help="Winsorization threshold for trait values, which limits the leverage of outliers; default 3.", label="Winsorize trait threshold", importance="default"),
        Section("Permutation null calibration"),
        FieldSpec(name="rer_perm_batches", help="Number of permutation batches; 0 skips the permutation null. Default 10.", label="Permutation batches", importance="default"),
        FieldSpec(name="rer_perms_per_batch", help="Permutations per batch; total null size is batches times this value. Default 100.", label="Permutations per batch", importance="default"),
        FieldSpec(name="rer_batch_seed", help="Seed of the null batches: batch i uses seed + i - 1, so fixing it reproduces the null; default 1998.", label="Null batch seed", importance="optional"),
        Section("Binary mode options"),
        FieldSpec(
            name="rer_binary_clade", help="Foreground branches for binary traits: all = every branch of the foreground clade, terminal = tips only, ancestral = internal branches only.",
            label="Binary foreground clade",
            kind="choice",
            choices=("all", "ancestral", "terminal"),
            importance="default",
        ),
        FieldSpec(name="rer_min_pos", help="Minimum independent foreground lineages a gene needs in binary mode; default 2.", label="Min independent foreground lineages", importance="default"),
        Section("Reporting and visualization thresholds"),
        FieldSpec(name="rer_top_n_labels", help="Number of top-ranked genes labeled on the correlation plot; default 20.", label="Top-N labels on correlation plot", importance="optional"),
        FieldSpec(name="rer_universe_file", help="Gene list defining the RER tested universe; blank falls back to the cleaned background.", label="RER tested-gene universe file", kind="path_file", importance="optional"),
        FieldSpec(name="rer_gene_scores", help="fcs_stats.tsv from SCORING; adds cross-module flags to the RER outputs.", label="Cross-module gene scores (fcs_stats.tsv)", kind="path_file", importance="optional"),
    ),
)


class RerConvergeTab(ModuleTabWidget):
    def __init__(self, config: RerConfig, parent=None):
        super().__init__(SPEC, config, parent)

        self.rer_tool_build_trait = QCheckBox("build_trait")
        self.rer_tool_build_trait.setChecked(config.rer_tool_build_trait)
        self.rer_tool_build_trait.toggled.connect(self._on_build_trait)

        self.rer_tool_build_tree = QCheckBox("build_tree")
        self.rer_tool_build_tree.setChecked(config.rer_tool_build_tree)
        self.rer_tool_build_tree.toggled.connect(self._on_build_tree)

        self.rer_tool_build_matrix = QCheckBox("build_matrix")
        self.rer_tool_build_matrix.setChecked(config.rer_tool_build_matrix)
        self.rer_tool_build_matrix.toggled.connect(self._on_build_matrix)

        self.rer_tool_continuous = QCheckBox("continuous")
        self.rer_tool_continuous.setChecked(config.rer_tool_continuous)
        self.rer_tool_continuous.toggled.connect(self._on_continuous)

        self._rer_tool_label = QLabel("RER tools (--rer_tool)")
        self._essential_form.insertRow(0, self._rer_tool_label, self.rer_tool_build_trait)
        self._essential_form.insertRow(1, "", self.rer_tool_build_tree)
        self._essential_form.insertRow(2, "", self.rer_tool_build_matrix)
        self._essential_form.insertRow(3, "", self.rer_tool_continuous)

    def retranslate(self, lang: str = "en") -> None:
        super().retranslate(lang)
        from gui.i18n import tr
        self._rer_tool_label.setText(tr("RER tools (--rer_tool)", lang))
        self.rer_tool_build_trait.setText(tr("build_trait", lang))
        self.rer_tool_build_tree.setText(tr("build_tree", lang))
        self.rer_tool_build_matrix.setText(tr("build_matrix", lang))
        self.rer_tool_continuous.setText(tr("continuous", lang))

    def _on_build_trait(self, value: bool) -> None:
        self._config.rer_tool_build_trait = value
        self.changed.emit()

    def _on_build_tree(self, value: bool) -> None:
        self._config.rer_tool_build_tree = value
        self.changed.emit()

    def _on_build_matrix(self, value: bool) -> None:
        self._config.rer_tool_build_matrix = value
        self.changed.emit()

    def _on_continuous(self, value: bool) -> None:
        self._config.rer_tool_continuous = value
        self.changed.emit()
