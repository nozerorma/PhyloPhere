# Identity checks catch same-size matrices with another tree, reordered columns or species.
trees <- list(masterTree=list(tip.label=c('A','B'),edge=matrix(1:4,2)),paths=matrix(1:4,1,dimnames=list(NULL,c('p1','p2','p3','p4'))),trees=list(g1=list()))
stamp <- rer_tree_contract(trees)
m <- matrix(1:4,1,dimnames=list('g1',stamp$paths))
attr(m,'rer_contract') <- list(version='rer_v1',tree=stamp$tree,paths=stamp$paths,genes='g1',species=c('A','B'))
rer_check_matrix(m,trees,c('A','B'))
t2<-trees;t2$masterTree$edge[1]<-9;fail(rer_check_matrix(m,t2,c('A','B')),'mismatch')
fail(rer_check_matrix(m,trees,c('A','C')),'mismatch')
m2<-m[,4:1,drop=FALSE];attr(m2,'rer_contract')<-attr(m,'rer_contract');fail(rer_check_matrix(m2,trees,c('A','B')),'mismatch')
attr(m,'rer_contract')<-NULL;fail(rer_check_matrix(m,trees,c('A','B')),'rebuild')
